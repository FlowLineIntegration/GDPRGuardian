//! Construction du site : gabarits découpés et contrôlés, valeurs de qualité écrites dans la langue de chaque page,
//! fichiers statiques précompressés (brotli, gzip) avec leurs ETag ; tout est embarqué dans le binaire.
//! Site build: templates split and checked, quality values written in each page's language, static files
//! precompressed (brotli, gzip) with their ETags; everything is embedded in the binary.
//!
//! Sources : site/templates/index.{fr,en}.html, site/static/**, site/data/quality.json. En construction de mise au
//! point, un fichier absent est remplacé par son jeu d'essai (site/tests/fixtures/site/…) avec un avertissement ; en
//! construction « release », c'est une erreur, sauf avec GDPRGUARDIAN_SITE_FIXTURES=1 ; avec
//! GDPRGUARDIAN_SITE_FIXTURES=force, les jeux d'essai remplacent tout. In a debug build a missing source falls back
//! to its fixture with a warning; in a release build it is an error unless GDPRGUARDIAN_SITE_FIXTURES=1; with
//! GDPRGUARDIAN_SITE_FIXTURES=force, fixtures replace everything.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::hash::Hasher;
use std::io::Write as _;
use std::path::{Path, PathBuf};

#[allow(dead_code)]
#[path = "src/format.rs"]
mod format;
#[allow(dead_code)]
#[path = "src/template.rs"]
mod template;

use format::Lang;
use template::{QValue, Seg};

fn main() {
    let root = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    for watched in [
        "build.rs",
        "src/format.rs",
        "src/template.rs",
        "templates",
        "static",
        "data",
        "tests/fixtures/site",
    ] {
        println!("cargo::rerun-if-changed={}", root.join(watched).display());
    }
    println!("cargo::rerun-if-env-changed=GDPRGUARDIAN_SITE_FIXTURES");

    let fixtures = root.join("tests/fixtures/site");
    // GDPRGUARDIAN_SITE_FIXTURES=force : jeux d'essai même si le site réel existe (essais du démon seul).
    // GDPRGUARDIAN_SITE_FIXTURES=force: fixtures even when the real site exists (daemon-only tests).
    let forced = env::var("GDPRGUARDIAN_SITE_FIXTURES").as_deref() == Ok("force");
    let mut substituted = Vec::new();
    let mut pick = |real: PathBuf, fixture: PathBuf, present: bool, name: &'static str| {
        if present && !forced {
            real
        } else {
            substituted.push(name);
            fixture
        }
    };
    let real_templates = root.join("templates");
    let templates_present = real_templates.join("index.fr.html").is_file()
        && real_templates.join("index.en.html").is_file();
    let templates = pick(
        real_templates,
        fixtures.join("templates"),
        templates_present,
        "templates/index.{fr,en}.html",
    );
    let static_present = root.join("static").is_dir();
    let static_dir = pick(
        root.join("static"),
        fixtures.join("static"),
        static_present,
        "static/",
    );
    let quality_present = root.join("data/quality.json").is_file();
    let quality_path = pick(
        root.join("data/quality.json"),
        fixtures.join("data/quality.json"),
        quality_present,
        "data/quality.json",
    );
    if !substituted.is_empty() {
        let release = env::var("PROFILE").as_deref() == Ok("release");
        if release && env::var_os("GDPRGUARDIAN_SITE_FIXTURES").is_none() {
            panic!(
                "site/{} absent(s) : construction « release » refusée avec des jeux d'essai (GDPRGUARDIAN_SITE_FIXTURES=1 \
                 pour passer outre) / missing: release build refused with fixtures",
                substituted.join(", site/")
            );
        }
        let why = if forced {
            "remplacé(s) / replaced"
        } else {
            "absent(s) / missing"
        };
        println!(
            "cargo::warning=site/{} {why} : jeux d'essai utilisés / fixtures used",
            substituted.join(", site/")
        );
    }

    let quality = read_quality(&quality_path);
    let mut code = String::with_capacity(1 << 20);
    code.push_str("// Produit par build.rs / generated by build.rs.\n");
    writeln!(code, "/// Vrai si des jeux d'essai remplacent le site réel / true when fixtures replace the real site.").unwrap();
    writeln!(
        code,
        "pub const USING_FIXTURES: bool = {};",
        !substituted.is_empty()
    )
    .unwrap();
    for (lang, file, ident) in [
        (Lang::Fr, "index.fr.html", "PAGE_FR"),
        (Lang::En, "index.en.html", "PAGE_EN"),
    ] {
        let path = templates.join(file);
        println!("cargo::rerun-if-changed={}", path.display());
        let source =
            fs::read_to_string(&path).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        let segs = template::compile(&source, &quality, lang)
            .unwrap_or_else(|errors| panic!("{}:\n  {}", path.display(), errors.join("\n  ")));
        writeln!(code, "pub static {ident}: &[Seg<&str>] = &[").unwrap();
        for seg in segs {
            match seg {
                Seg::Lit(text) => writeln!(code, "    Seg::Lit({text:?}),").unwrap(),
                Seg::Live(live) => {
                    writeln!(code, "    Seg::Live(Live::{}),", live.ident()).unwrap()
                }
            }
        }
        code.push_str("];\n");
    }

    let mut files = Vec::new();
    walk(&static_dir, &static_dir, &mut files);
    files.sort();
    let compressed = out.join("compressed");
    fs::create_dir_all(&compressed).expect("OUT_DIR/compressed");
    code.push_str("pub static ASSETS: &[Asset] = &[\n");
    for (index, (relative, path)) in files.iter().enumerate() {
        println!("cargo::rerun-if-changed={}", path.display());
        let data = fs::read(path).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        let content_type = content_type(relative);
        let mut hasher = siphasher::sip::SipHasher13::new();
        hasher.write(&data);
        let tag = format!("{:016x}", hasher.finish());
        let variant = |suffix: &str, encoded: Option<Vec<u8>>| -> String {
            // Gardée seulement si elle gagne au moins 5 % / kept only when it saves at least 5 %.
            match encoded {
                Some(encoded) if encoded.len() * 20 < data.len() * 19 => {
                    let target = compressed.join(format!("{index}.{suffix}"));
                    fs::write(&target, encoded).expect("OUT_DIR write");
                    format!("Some(include_bytes!({:?}))", target.display().to_string())
                }
                _ => String::from("None"),
            }
        };
        let compressible = is_compressible(relative);
        let br = variant("br", compressible.then(|| brotli_bytes(&data)));
        let gzip = variant("gz", compressible.then(|| gzip_bytes(&data)));
        writeln!(
            code,
            "    Asset {{ path: {relative:?}, content_type: {content_type:?}, etag: {:?}, etag_br: {:?}, etag_gzip: {:?}, \
             identity: include_bytes!({:?}), br: {br}, gzip: {gzip} }},",
            format!("\"{tag}\""),
            format!("\"{tag}-br\""),
            format!("\"{tag}-gz\""),
            path.display().to_string(),
        )
        .unwrap();
    }
    code.push_str("];\n");
    fs::write(out.join("embedded.rs"), code).expect("OUT_DIR/embedded.rs");
}

/// quality.json : objet plat de nombres (texte d'origine gardé) et de chaînes / flat object of numbers and strings.
fn read_quality(path: &Path) -> BTreeMap<String, QValue> {
    println!("cargo::rerun-if-changed={}", path.display());
    let text =
        fs::read_to_string(path).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
    let raw: BTreeMap<String, Box<serde_json::value::RawValue>> = serde_json::from_str(&text)
        .unwrap_or_else(|error| {
            panic!(
                "{}: objet plat attendu / flat object: {error}",
                path.display()
            )
        });
    let quality: BTreeMap<String, QValue> = raw
        .into_iter()
        .map(|(key, value)| {
            let value = value.get().trim();
            let parsed = if value.starts_with('"') {
                QValue::Str(serde_json::from_str(value).expect("chaîne JSON / JSON string"))
            } else if format::decimal_text(value, Lang::En).is_some() {
                QValue::Num(value.to_string())
            } else {
                panic!("{}: « {key} » : nombre décimal ou chaîne attendu / decimal number or string expected, got {value}", path.display());
            };
            (key, parsed)
        })
        .collect();
    // Contrat D : valeurs du protocole public « — » ou bien formées / public protocol values pending or well formed.
    let errors = template::contract_errors(&quality);
    if !errors.is_empty() {
        panic!("{}:\n  {}", path.display(), errors.join("\n  "));
    }
    quality
}

/// Fichiers de `dir`, chemins relatifs en « / », fichiers cachés ignorés / files, relative "/" paths, hidden skipped.
fn walk(base: &Path, dir: &Path, files: &mut Vec<(String, PathBuf)>) {
    let entries = fs::read_dir(dir).unwrap_or_else(|error| panic!("{}: {error}", dir.display()));
    for entry in entries {
        let path = entry.expect("read_dir").path();
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or_default();
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            walk(base, &path, files);
            continue;
        }
        let relative = path
            .strip_prefix(base)
            .expect("prefix")
            .components()
            .map(|part| {
                part.as_os_str()
                    .to_str()
                    .unwrap_or_else(|| panic!("{}: nom non UTF-8 / non UTF-8 name", path.display()))
                    .to_string()
            });
        let relative: Vec<String> = relative.collect();
        let relative = relative.join("/");
        // Chemin servi tel quel dans l'URL : caractères sûrs seulement / served as is in the URL: safe characters only.
        if !relative
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || b"._-/".contains(&byte))
        {
            panic!(
                "{}: nom de fichier hors [A-Za-z0-9._-] / file name outside [A-Za-z0-9._-]",
                path.display()
            );
        }
        files.push((relative, path));
    }
}

fn extension(relative: &str) -> String {
    relative
        .rsplit_once('.')
        .map(|(_, extension)| extension.to_ascii_lowercase())
        .unwrap_or_default()
}

fn content_type(relative: &str) -> &'static str {
    match extension(relative).as_str() {
        "css" => "text/css; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "svg" => "image/svg+xml",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "webp" => "image/webp",
        "avif" => "image/avif",
        "gif" => "image/gif",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "woff" => "font/woff",
        "ttf" => "font/ttf",
        "otf" => "font/otf",
        "json" | "map" => "application/json",
        "webmanifest" => "application/manifest+json",
        "txt" => "text/plain; charset=utf-8",
        "html" => "text/html; charset=utf-8",
        "xml" => "application/xml",
        "pdf" => "application/pdf",
        other => {
            println!(
                "cargo::warning=site/static/{relative}: extension « {other} » inconnue, application/octet-stream"
            );
            "application/octet-stream"
        }
    }
}

/// Formats textuels (les images et polices WOFF sont déjà compressées) / text formats (images, WOFF already are).
fn is_compressible(relative: &str) -> bool {
    matches!(
        extension(relative).as_str(),
        "css"
            | "js"
            | "mjs"
            | "svg"
            | "json"
            | "map"
            | "webmanifest"
            | "txt"
            | "html"
            | "xml"
            | "ico"
            | "ttf"
            | "otf"
    )
}

fn brotli_bytes(data: &[u8]) -> Vec<u8> {
    let mut writer = brotli::CompressorWriter::new(Vec::new(), 4096, 11, 22);
    writer.write_all(data).expect("brotli");
    writer.into_inner()
}

fn gzip_bytes(data: &[u8]) -> Vec<u8> {
    let mut encoder = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
    encoder.write_all(data).expect("gzip");
    encoder.finish().expect("gzip")
}
